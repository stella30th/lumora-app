CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(50)  NOT NULL,
    email         VARCHAR(255) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    created_at    TIMESTAMP(6) NOT NULL,
    CONSTRAINT uk_users_username UNIQUE (username),
    CONSTRAINT uk_users_email UNIQUE (email)
);

CREATE TABLE decks (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(100) NOT NULL,
    description VARCHAR(500),
    is_public   BOOLEAN      NOT NULL,
    owner_id    BIGINT       NOT NULL,
    created_at  TIMESTAMP(6) NOT NULL,
    CONSTRAINT fk_decks_owner FOREIGN KEY (owner_id) REFERENCES users (id)
);

CREATE TABLE cards (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    term       VARCHAR(255)  NOT NULL,
    definition VARCHAR(1000) NOT NULL,
    deck_id    BIGINT        NOT NULL,
    created_at TIMESTAMP(6)  NOT NULL,
    CONSTRAINT fk_cards_deck FOREIGN KEY (deck_id) REFERENCES decks (id)
);

CREATE TABLE card_progress (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          BIGINT           NOT NULL,
    card_id          BIGINT           NOT NULL,
    ease_factor      DOUBLE PRECISION NOT NULL,
    interval_days    INTEGER          NOT NULL,
    repetitions      INTEGER          NOT NULL,
    status           VARCHAR(20)      NOT NULL,
    next_review_date DATE             NOT NULL,
    last_reviewed_at TIMESTAMP(6),
    CONSTRAINT uk_card_progress_user_card UNIQUE (user_id, card_id),
    CONSTRAINT ck_card_progress_status CHECK (status IN ('NEW', 'LEARNING', 'REVIEW')),
    CONSTRAINT fk_card_progress_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_card_progress_card FOREIGN KEY (card_id) REFERENCES cards (id)
);

CREATE TABLE review_log (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT       NOT NULL,
    card_id     BIGINT       NOT NULL,
    correct     BOOLEAN      NOT NULL,
    reviewed_at TIMESTAMP(6) NOT NULL,
    CONSTRAINT fk_review_log_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_review_log_card FOREIGN KEY (card_id) REFERENCES cards (id)
);

CREATE INDEX idx_review_log_user_reviewed_at ON review_log (user_id, reviewed_at);

CREATE TABLE refresh_tokens (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT       NOT NULL,
    token      VARCHAR(255) NOT NULL,
    expires_at TIMESTAMP(6) NOT NULL,
    revoked    BOOLEAN      NOT NULL,
    created_at TIMESTAMP(6) NOT NULL,
    CONSTRAINT uk_refresh_tokens_token UNIQUE (token),
    CONSTRAINT fk_refresh_tokens_user FOREIGN KEY (user_id) REFERENCES users (id)
);
